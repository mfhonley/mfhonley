export function formatNotes(item) {
  return [
    `ОПОРА: ${item.anchor}`,
    ...item.points.map(point => `• ${point}`),
    item.example ? `ПРИМЕР\n${item.example}` : '',
    item.transition ? `ПЕРЕХОД\n${item.transition}` : '',
  ].filter(Boolean).join('\n\n');
}
